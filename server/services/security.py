import hmac
import hashlib
import logging
from config import settings

logger = logging.getLogger("security")

def verify_subscription_token(mode: str, token: str) -> bool:
    """
    Validates Meta webhook verification challenge query params.
    """
    if mode == "subscribe" and token == settings.WHATSAPP_VERIFY_TOKEN:
        return True
    return False

def verify_meta_signature(payload_bytes: bytes, signature_header: str) -> bool:
    """
    Verifies that the incoming webhook POST payload matches the HMAC-SHA256 signature
    generated by Meta using your WHATSAPP_APP_SECRET.
    Format of header: 'sha256=<hex_digest>'
    """
    if not settings.WHATSAPP_APP_SECRET:
        # In development without an App Secret configured, allow payloads through
        return True
        
    if not signature_header or not signature_header.startswith("sha256="):
        logger.warning("Missing or malformed X-Hub-Signature-256 header")
        return False
        
    expected_hash = signature_header.split("sha256=", 1)[1]
    calculated_hmac = hmac.new(
        key=settings.WHATSAPP_APP_SECRET.encode("utf-8"),
        msg=payload_bytes,
        digestmod=hashlib.sha256
    ).hexdigest()
    
    return hmac.compare_digest(expected_hash, calculated_hmac)
